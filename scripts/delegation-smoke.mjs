// All writes occur in an isolated Postgres schema and temporary ledger directory.
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {randomUUID} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {mkdtemp, readFile, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(new URL('../server/package.json', import.meta.url));
require('dotenv').config({path:join(root,'server/.env'), quiet:true});
const {PrismaClient}=require('@prisma/client');
const {DelegationRepository}=require('./dist/modules/delegation/delegation.repository.js');
const {DelegationService}=require('./dist/modules/delegation/delegation.service.js');
const {DelegatedResultService}=require('./dist/modules/delegation/result.service.js');
const {AgentStore}=require('./dist/modules/agent-runs/agent.store.js');
const {AgentLeaseRepository}=require('./dist/modules/agent-runs/lease.repository.js');
const schema = 'smoke_delegation_'+randomUUID().replaceAll('-','');
const admin = new PrismaClient();
const url = new URL(process.env.DATABASE_URL); url.searchParams.set('schema', schema);
const db = new PrismaClient({datasourceUrl:url.toString()});
const tmp = await mkdtemp(join(tmpdir(),'snk-delegation-'));
const oldLedger = process.env.BAW_MINT_LEDGER_PATH;
process.env.BAW_MINT_LEDGER_PATH=join(tmp,'ledger.json');
const scope = n => 'EVM:0x'+String(n).repeat(40);
const hash = '0x'+'a'.repeat(64), address='0x'+'3'.repeat(40);
try {
  await admin.$executeRawUnsafe(`CREATE SCHEMA "${schema}"`);
  execFileSync(process.execPath,[join(root,'server/node_modules/prisma/build/index.js'),'migrate','deploy'],{cwd:join(root,'server'),env:{...process.env,DATABASE_URL:url.toString()},stdio:'pipe'});
  const repo = new DelegationRepository(db), store = new AgentStore(db,new AgentLeaseRepository(db));
  const service = new DelegationService(repo,{gates:async()=>({priceWei:'0',holders:101,holdersVerified:true,previewRequired:true,agentMustRevalidate:true})},store);
  await repo.createExecutor({id:'w1',walletScope:scope(1),role:'FREE_MINT',isDefault:true,label:'Legacy free'});
  await repo.session('w1',{walletScope:scope(1),state:'CONNECTED'});
  await assert.rejects(()=>repo.createExecutor({id:'w2',walletScope:scope(1),role:'PAID',isDefault:true,label:'Duplicate'}),e=>e.code==='SESSION_SHARED');
  await repo.createExecutor({id:'w2',walletScope:scope(2),role:'PAID',isDefault:true,label:'Legacy paid'});
  await repo.session('w2',{walletScope:scope(2),state:'UNCONNECTED'});
  const candidate = await store.addCandidate({chainId:'56',contractAddress:address,class:'FREE_MINT',inputData:'0x12345678',source:'SMOKE_FIXTURE'});
  const row = await service.queue(candidate.id);
  assert.equal(row.kind,'FREE_MINT');
  assert.equal((await service.queue(candidate.id)).id,row.id);
  const claimInput={executorId:'w1',walletScope:scope(1)};
  await assert.rejects(()=>repo.claim(row.id,{executorId:'w2',walletScope:scope(2)}),e=>e.code==='EXECUTOR_OFFLINE');
  const claims = await Promise.allSettled([repo.claim(row.id,claimInput),repo.claim(row.id,claimInput)]);
  assert.equal(claims.filter(r=>r.status==='fulfilled').length,1);
  const claimed = claims.find(r=>r.status==='fulfilled').value;
  const rpc={receipt:async()=>({status:'0x1',blockNumber:'0x1'}),call:async(method,params)=>method==='eth_chainId'?'0x38':method==='eth_getBlockByNumber'?{timestamp:'0x69000000'}:{from:(params[0] === '0x'+'b'.repeat(64) ? scope(2) : scope(1)).slice(4),to:address,value:'0x0',input:'0x12345678'}};
  const results = new DelegatedResultService(repo,rpc,store);
  const result={...claimInput,claimToken:claimed.claimToken,status:'SUCCEEDED',txHash:hash,previewClean:true,priceWei:'0',holders:101,previewRequestId:'isolated_fixture'};
  await assert.rejects(()=>results.result(row.id,{...result,walletScope:scope(2)}),e=>e.code==='OUTBOX_NOT_FOUND');
  await results.result(row.id,result); await results.result(row.id,result);
  assert.equal(await db.walletActivity.count(),1);
  assert.equal((await db.agentRun.findUnique({where:{id:claimed.runId}})).status,'SUCCEEDED');
  const ledger=JSON.parse(await readFile(process.env.BAW_MINT_LEDGER_PATH,'utf8'));
  assert.equal(ledger.mints.length,1); assert.equal(ledger.mints[0].walletScope,scope(1));
  execFileSync(process.execPath,[join(root,'scripts/import-baw-free-mints.mjs'),'--file',process.env.BAW_MINT_LEDGER_PATH],{env:{...process.env,DATABASE_URL:url.toString()},stdio:'pipe'});
  assert.equal(await db.walletActivity.count(),1);
  // A second wallet may hold the same tx hash as a separate imported ledger partition.
  const {writeFile}=await import('node:fs/promises');
  ledger.mints.push({...ledger.mints[0],walletScope:scope(2),walletAddress:scope(2).slice(4)});
  await writeFile(process.env.BAW_MINT_LEDGER_PATH,JSON.stringify(ledger));
  execFileSync(process.execPath,[join(root,'scripts/import-baw-free-mints.mjs'),'--file',process.env.BAW_MINT_LEDGER_PATH],{env:{...process.env,DATABASE_URL:url.toString()},stdio:'pipe'});
  assert.equal(await db.walletActivity.count(),2);
  // Legacy checksum casing must normalize to the same DB partitions on import.
  const checksumWallet='0x'+'aB'.repeat(20);
  ledger.walletAddress=checksumWallet;
  ledger.walletScope='EVM:'+checksumWallet;
  ledger.mints.push({...ledger.mints[0],walletScope:'EVM:'+checksumWallet,walletAddress:checksumWallet});
  await writeFile(process.env.BAW_MINT_LEDGER_PATH,JSON.stringify(ledger));
  execFileSync(process.execPath,[join(root,'scripts/import-baw-free-mints.mjs'),'--file',process.env.BAW_MINT_LEDGER_PATH],{env:{...process.env,DATABASE_URL:url.toString()},stdio:'pipe'});
  assert.equal(await db.walletActivity.count(),3);
  assert.equal(await db.walletActivity.count({where:{walletScope:'EVM:'+checksumWallet.toLowerCase()}}),1);
  // Unknown work cannot be reclaimed, including after restart/expiry.
  const c2=await store.addCandidate({chainId:'56',contractAddress:'0x'+'4'.repeat(40),class:'FREE_MINT',inputData:'0x12345678',source:'SMOKE_FIXTURE'});
  const q2=await service.queue(c2.id), claim2=await repo.claim(q2.id,claimInput);
  await results.result(q2.id,{...claimInput,claimToken:claim2.claimToken,status:'UNKNOWN'});
  await assert.rejects(()=>repo.claim(q2.id,claimInput));
  await store.recover();
  assert.equal((await db.candidateOutbox.findUnique({where:{id:q2.id}})).status,'UNKNOWN');
  // Paid intent is recorded offline; claiming consumes it only after w2 reconnects.
  const paid=await store.addCandidate({chainId:'56',contractAddress:'0x'+'5'.repeat(40),class:'PAID_TOKEN',source:'SMOKE_FIXTURE'});
  const researchRun=await store.createRun('RESEARCH','USER',paid.id);
  const brief=await store.createBrief({candidateId:paid.id,runId:researchRun.id,chainId:'56',contractAddress:paid.contractAddress,bodyMd:'Isolated paid fixture',auditAvailable:true,dynamicAvailable:true,riskLevel:'LOW',evidenceJson:{audit:{available:true,severity:1}}});
  const buyInput={walletScope:scope(2),amount:'0.01',asset:'BNB',slippage:'auto',confirmationText:'确认买入 0.01 BNB'};
  await assert.rejects(()=>service.confirm(brief.id,{...buyInput,confirmationText:'买一点'}),e=>e.code==='CONFIRM_REQUIRED');
  const buy=await service.confirm(brief.id,buyInput);
  await assert.rejects(()=>repo.claim(buy.id,{executorId:'w2',walletScope:scope(2)}),e=>e.code==='EXECUTOR_OFFLINE');
  await repo.session('w2',{walletScope:scope(2),state:'CONNECTED'});
  const buyClaim=await repo.claim(buy.id,{executorId:'w2',walletScope:scope(2)});
  await assert.rejects(()=>repo.claim(buy.id,{executorId:'w2',walletScope:scope(2)}));
  const paidResult={executorId:'w2',walletScope:scope(2),claimToken:buyClaim.claimToken,status:'SUCCEEDED',txHash:'0x'+'b'.repeat(64),orderId:'fixture_order',orderStatus:'COMPLETED'};
  await results.result(buy.id,paidResult);
  assert.equal(await db.walletActivity.count({where:{walletScope:scope(2),type:'TRADE'}}),1);
  assert.equal((await db.candidateOutbox.findUnique({where:{id:buy.id}})).status,'SUCCEEDED');
  // Exercise HTTP DTOs and scope projection against the same isolated schema.
  const {Test}=require('@nestjs/testing');
  const {AppModule}=require('./dist/app.module.js');
  const {PrismaService}=require('./dist/prisma/prisma.service.js');
  const {BawService}=require('./dist/modules/wallet/baw.service.js');
  const {setupApp}=require('./dist/common/setup-app.js');
  const previousNodeEnv=process.env.NODE_ENV; process.env.NODE_ENV='test';
  let app;
  try {
    const module=await Test.createTestingModule({imports:[AppModule]}).overrideProvider(PrismaService).useValue(db).overrideProvider(BawService).useValue({run:()=>{throw new Error('Wallet CLI must never be called');}}).compile();
    app=module.createNestApplication({logger:false}); setupApp(app); await app.listen(0,'127.0.0.1');
    const base=`http://127.0.0.1:${app.getHttpServer().address().port}/api/v1`;
    const get=async path=>{const response=await fetch(base+path); return {status:response.status,body:await response.json()};};
    const identity=await get('/wallet/identity?walletScope='+scope(2)); assert.equal(identity.body.data.scope,scope(2));
    const runs=await get('/agent/runs?walletScope='+scope(2)); assert.ok(runs.body.data.items.some(r=>r.id===buyClaim.runId)); assert.ok(!runs.body.data.items.some(r=>r.id===claimed.runId));
    assert.equal((await get('/agent/runs/'+claimed.runId+'?walletScope='+scope(2))).status,404);
    assert.equal((await get('/wallet/identity?walletScope=bad')).status,400);
    const outbox=await get('/delegation/outbox?executorId=w1'); assert.equal(outbox.status,200); assert.ok(!JSON.stringify(outbox.body).includes('claimToken'));
    const unknownRole=await fetch(base+'/delegation/sessions/INVALID_ID',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({walletScope:scope(1),state:'CONNECTED'})}); assert.equal(unknownRole.status,400);
    const register=await fetch(base+'/delegation/executors',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({id:'w9',walletScope:scope(9),role:'MONITOR',label:'HTTP monitor'})}); assert.equal(register.status,201);
    assert.equal((await register.json()).data.state,'UNCONNECTED');
    const invalid=await fetch(base+'/delegation/executors',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({id:'bad id',walletScope:scope(8),role:'MONITOR'})}); assert.equal(invalid.status,400);
    const invalidNull=await fetch(base+'/delegation/executors',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({id:'null_input',walletScope:scope(8),role:'MONITOR',isDefault:null})}); assert.equal(invalidNull.status,400);
    const edit=await fetch(base+'/delegation/executors/w9',{method:'PATCH',headers:{'Content-Type':'application/json'},body:JSON.stringify({label:'Updated HTTP monitor',paused:true})}); assert.equal(edit.status,200);
    assert.equal((await edit.json()).data.paused,true);
    const online=await fetch(base+'/delegation/sessions/w9',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({walletScope:scope(9),state:'CONNECTED'})}); assert.equal(online.status,201);
    const registered=await get('/delegation/sessions'); assert.ok(registered.body.data.some(s=>s.id==='w9'&&s.label==='Updated HTTP monitor'&&s.role==='MONITOR'&&!s.online));
    const noConfirm=await fetch(base+'/delegation/briefs/'+brief.id+'/confirm-buy',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({walletScope:scope(2),amount:'1',asset:'BNB',confirmationText:'买一点'})}); assert.equal(noConfirm.status,409);
  } finally {if(app) await app.close(); if(previousNodeEnv===undefined) delete process.env.NODE_ENV; else process.env.NODE_ENV=previousNodeEnv;}
  const {verifyDynamicExecutors}=await import('./dynamic-executors-smoke.mjs');
  await verifyDynamicExecutors({repo,db,service,store});
  await repo.session('w1',{walletScope:scope(1),state:'UNCONNECTED'});
  assert.ok(await db.agentNotification.count({where:{message:{contains:'UNCONNECTED'}}}));
  console.log('PASS: isolated delegation DB — independent sessions, offline pause, atomic claim, receipt callback, ledger write/import dedup, multi-wallet partitions, UNKNOWN no replay, paid intent/terminal result, HTTP scope and validation');
} finally {
  if(oldLedger===undefined) delete process.env.BAW_MINT_LEDGER_PATH; else process.env.BAW_MINT_LEDGER_PATH=oldLedger;
  await db.$disconnect();
  await admin.$executeRawUnsafe(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`); await admin.$disconnect();
  await rm(tmp,{recursive:true,force:true});
}
