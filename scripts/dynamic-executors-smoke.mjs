import assert from 'node:assert/strict';
export async function verifyDynamicExecutors({repo,db,service,store}) {
  const scope=n=>'EVM:0x'+String(n).repeat(40);
  await repo.createExecutor({id:'w3',walletScope:scope(6),label:'Monitor wallet',role:'MONITOR',isDefault:false,sourceRoles:['STANDBY','COLLAB'],agentId:'fixture.ai'});
  await repo.createExecutor({id:'w4',walletScope:scope(7),label:'Dynamic free wallet',role:'FREE_MINT',isDefault:false});
  const metadata=await repo.sessionById('w3');
  assert.equal(metadata.state,'UNCONNECTED'); assert.deepEqual(metadata.sourceRoles,['STANDBY','COLLAB']); assert.equal(metadata.agentId,'fixture.ai');
  await repo.session('w3',{walletScope:scope(6),state:'CONNECTED'});
  await assert.rejects(()=>repo.selectExecutor('FREE_MINT','w3'),e=>e.code==='EXECUTOR_ROLE');
  await assert.rejects(()=>repo.session('w4',{walletScope:scope(6),state:'CONNECTED'}),e=>e.code==='EXECUTOR_WALLET_BOUND');
  assert.equal((await repo.selectExecutor('FREE_MINT')).id,'w1');
  await repo.updateExecutor('w4',{isDefault:true});
  assert.equal((await repo.selectExecutor('FREE_MINT')).id,'w4');
  assert.equal((await repo.sessionById('w1')).isDefault,false);
  const candidate=await store.addCandidate({chainId:'56',contractAddress:'0x'+'6'.repeat(40),class:'FREE_MINT',inputData:'0x12345678',source:'SMOKE_FIXTURE'});
  const task=await service.queue(candidate.id);
  assert.equal(task.executorId,'w4'); assert.equal(task.walletScope,scope(7));
  await repo.updateExecutor('w1',{isDefault:true});
  assert.equal((await service.queue(candidate.id)).executorId,'w4');
  await assert.rejects(()=>service.queue(candidate.id,'w1'),e=>e.code==='OUTBOX_BOUND');
  await assert.rejects(()=>repo.updateExecutor('w4',{role:'MONITOR'}),e=>e.code==='EXECUTOR_BUSY');
  await assert.rejects(()=>repo.claim(task.id,{executorId:'w4',walletScope:scope(7)}),e=>e.code==='EXECUTOR_OFFLINE');
  await repo.session('w4',{walletScope:scope(7),state:'CONNECTED'});
  await repo.updateExecutor('w4',{paused:true,label:'Paused dynamic wallet'});
  await repo.session('w4',{walletScope:scope(7),state:'CONNECTED'});
  assert.equal((await repo.sessionById('w4')).paused,true);
  await assert.rejects(()=>repo.session('w4',{walletScope:scope(7),state:'CONNECTED',paused:false}),e=>e.code==='EXECUTOR_CONFIG_REQUIRED');
  await assert.rejects(()=>repo.claim(task.id,{executorId:'w4',walletScope:scope(7)}),e=>e.code==='EXECUTOR_OFFLINE');
  await repo.updateExecutor('w4',{paused:false});
  const claimed=await repo.claim(task.id,{executorId:'w4',walletScope:scope(7)});
  assert.equal(claimed.executorId,'w4');
  await assert.rejects(()=>repo.updateExecutor('w4',{role:'PAID'}),e=>e.code==='EXECUTOR_BUSY');
  await Promise.all([repo.updateExecutor('w4',{isDefault:true}),repo.updateExecutor('w1',{isDefault:true})]);
  assert.equal(await db.executorSession.count({where:{role:'FREE_MINT',isDefault:true}}),1);
  await repo.updateExecutor('w1',{isDefault:false});
  await repo.updateExecutor('w4',{isDefault:false});
  await assert.rejects(()=>repo.selectExecutor('FREE_MINT'),e=>e.code==='EXECUTOR_REQUIRED');
  await repo.updateExecutor('w3',{role:'PAID',label:'Converted paid wallet'});
  const paid=await store.addCandidate({chainId:'56',contractAddress:'0x'+'7'.repeat(40),class:'PAID_TOKEN',source:'SMOKE_FIXTURE'});
  const run=await store.createRun('RESEARCH','USER',paid.id);
  const brief=await store.createBrief({candidateId:paid.id,runId:run.id,chainId:'56',contractAddress:paid.contractAddress,bodyMd:'Dynamic paid fixture',auditAvailable:true,dynamicAvailable:true,riskLevel:'LOW',evidenceJson:{audit:{available:true,severity:1}}});
  const intent=await service.confirm(brief.id,{walletScope:scope(6),amount:'0.01',asset:'BNB',slippage:'auto',confirmationText:'确认买入 0.01 BNB'});
  assert.equal(intent.executorId,'w3'); assert.equal(intent.walletScope,scope(6));
  console.log('PASS: dynamic executors — w3/w4 registration, monitor-only role, default routing, no reassignment/failover, protected pause, role-change guards, concurrent defaults, dynamic paid intent');
}
